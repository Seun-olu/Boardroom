import { z } from "zod";
import type { ClientMessage } from "./types";

/**
 * Runtime validation for everything that crosses the network boundary into
 * the board API. Types in `types.ts` describe the shape; these schemas enforce
 * it, plus size limits so a single request can't balloon the board document.
 */

export const LIMITS = {
  roomId: 64,
  id: 80,
  title: 200,
  description: 10_000,
  userName: 60,
  boardName: 120,
  subtasks: 100,
  subtaskTitle: 200,
  flushQueue: 100,
  maxOrder: 10_000,
  maxVersion: 1_000_000_000,
  /** Raw request body cap. A full 100-action flush comfortably fits. */
  bodyBytes: 256 * 1024,
} as const;

/** Room ids are generated by `generateRoomId`: lowercase slug + "-" + 6 hex chars. */
export const roomIdSchema = z
  .string()
  .min(1)
  .max(LIMITS.roomId)
  .regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, "Invalid board id");

const id = z.string().min(1).max(LIMITS.id).regex(/^[A-Za-z0-9_-]+$/, "Invalid id");
const clientActionId = z.string().min(1).max(LIMITS.id);
const userName = z.string().trim().min(1).max(LIMITS.userName);
const title = z.string().trim().min(1).max(LIMITS.title);
const version = z.number().int().min(0).max(LIMITS.maxVersion);
const order = z.number().int().min(0).max(LIMITS.maxOrder);
const color = z.string().regex(/^#[0-9A-Fa-f]{6}$/, "Invalid color");
const priority = z.enum(["low", "medium", "high", "urgent"]);
const storyPoints = z.number().min(0).max(100).nullable();
const template = z.enum(["blank", "default", "empty", "software"]);

const subtask = z.strictObject({
  id,
  title: z.string().trim().min(1).max(LIMITS.subtaskTitle),
  done: z.boolean(),
});

export const initBoardSchema = z.strictObject({
  type: z.literal("init_board"),
  name: z.string().trim().max(LIMITS.boardName),
  template,
});

export const updateBoardSchema = z.strictObject({
  type: z.literal("update_board"),
  name: z.string().trim().min(1).max(LIMITS.boardName),
  expectedVersion: version,
  userName,
  clientActionId,
});

export const moveCardSchema = z.strictObject({
  type: z.literal("move_card"),
  cardId: id,
  column: id,
  order,
  expectedVersion: version,
  timestamp: z.number().int().positive(),
  userName,
  clientActionId,
});

export const addCardSchema = z.strictObject({
  type: z.literal("add_card"),
  title,
  description: z.string().max(LIMITS.description).optional(),
  priority: priority.optional(),
  storyPoints: storyPoints.optional(),
  column: id,
  clientActionId,
  userName,
});

export const updateCardSchema = z.strictObject({
  type: z.literal("update_card"),
  cardId: id,
  title: title.optional(),
  description: z.string().max(LIMITS.description).optional(),
  priority: priority.optional(),
  storyPoints: storyPoints.optional(),
  subtasks: z.array(subtask).max(LIMITS.subtasks).optional(),
  expectedVersion: version,
  userName,
  clientActionId,
});

export const addColumnSchema = z.strictObject({
  type: z.literal("add_column"),
  title,
  color,
  clientActionId,
  userName,
});

export const deleteCardSchema = z.strictObject({
  type: z.literal("delete_card"),
  cardId: id,
  expectedVersion: version,
  userName,
  clientActionId,
});

export const deleteColumnSchema = z.strictObject({
  type: z.literal("delete_column"),
  columnId: id,
  expectedVersion: version,
  userName,
  clientActionId,
});

export const updateColumnSchema = z.strictObject({
  type: z.literal("update_column"),
  columnId: id,
  title: title.optional(),
  color: color.optional(),
  expectedVersion: version,
  userName,
  clientActionId,
});

export const moveColumnSchema = z.strictObject({
  type: z.literal("move_column"),
  columnId: id,
  order,
  expectedVersion: version,
  userName,
  clientActionId,
});

/** Actions that may appear inside a flush_queue (never init or nested flushes). */
export const queueableActionSchema = z.discriminatedUnion("type", [
  updateBoardSchema,
  moveCardSchema,
  addCardSchema,
  updateCardSchema,
  addColumnSchema,
  deleteCardSchema,
  deleteColumnSchema,
  updateColumnSchema,
  moveColumnSchema,
]);

export const flushQueueSchema = z.strictObject({
  type: z.literal("flush_queue"),
  actions: z.array(queueableActionSchema).min(1).max(LIMITS.flushQueue),
});

export const clientMessageSchema = z.discriminatedUnion("type", [
  initBoardSchema,
  ...queueableActionSchema.options,
  flushQueueSchema,
]);

// Compile-time guarantee that the schema and the hand-written union stay in sync.
// If either direction stops being assignable, `tsc` fails on these aliases.
type Parsed = z.infer<typeof clientMessageSchema>;
type AssertTrue<T extends true> = T;
export type SchemaMatchesTypes = AssertTrue<
  [ClientMessage] extends [Parsed] ? ([Parsed] extends [ClientMessage] ? true : false) : false
>;

export type ValidationResult<T> =
  | { ok: true; data: T }
  | { ok: false; status: 400 | 413; error: string; issues?: string[] };

/** Formats Zod issues as short "path: message" strings safe to return to clients. */
function formatIssues(error: z.ZodError): string[] {
  return error.issues
    .slice(0, 10)
    .map((i) => `${i.path.join(".") || "(root)"}: ${i.message}`);
}

export function parseRoomId(raw: string): ValidationResult<string> {
  const result = roomIdSchema.safeParse(raw);
  return result.success
    ? { ok: true, data: result.data }
    : { ok: false, status: 400, error: "Invalid board id" };
}

/**
 * Reads and validates an action request body. Enforces the byte limit on the
 * raw text before JSON.parse so oversized payloads are rejected cheaply.
 */
export async function parseClientMessage(
  request: Request
): Promise<ValidationResult<ClientMessage>> {
  const declared = Number(request.headers.get("content-length") ?? "0");
  if (declared > LIMITS.bodyBytes) {
    return { ok: false, status: 413, error: "Payload too large" };
  }

  let text: string;
  try {
    text = await request.text();
  } catch {
    return { ok: false, status: 400, error: "Unreadable body" };
  }
  if (new TextEncoder().encode(text).byteLength > LIMITS.bodyBytes) {
    return { ok: false, status: 413, error: "Payload too large" };
  }

  let json: unknown;
  try {
    json = JSON.parse(text);
  } catch {
    return { ok: false, status: 400, error: "Invalid JSON" };
  }

  const result = clientMessageSchema.safeParse(json);
  if (!result.success) {
    return {
      ok: false,
      status: 400,
      error: "Invalid action",
      issues: formatIssues(result.error),
    };
  }
  return { ok: true, data: result.data };
}
